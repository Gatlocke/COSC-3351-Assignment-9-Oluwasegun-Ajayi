export function validateItem(body, isUpdate = false) {
  if (body === null || typeof body !== "object" || Array.isArray(body)) {
    return "Request body must be a JSON object.";
  }
  const fields = Object.keys(body);
  if (fields.includes("id")) {
    return "id is generated by the database and cannot be supplied or changed.";
  }
  if (fields.some((field) => !["title", "completed"].includes(field))) {
    return "Only title and completed are supported fields.";
  }
  if (isUpdate && fields.length === 0) {
    return "Provide at least one field: title or completed.";
  }
  if (!isUpdate || Object.hasOwn(body, "title")) {
    if (typeof body.title !== "string" || !body.title.trim()
        || [...body.title.trim()].length > 120) {
      return "title must be a non-empty string of at most 120 characters.";
    }
    if (body.title.includes("\0")) return "title cannot contain a null character.";
  }
  if (Object.hasOwn(body, "completed") && typeof body.completed !== "boolean") {
    return "completed must be a boolean.";
  }
  return null;
}
